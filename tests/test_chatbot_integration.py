"""Integration test for the chatbot (spec section 8): the 5 sample queries.

Requires real Ollama (qwen3:4b + qwen3-embedding:4b) and the Neo4j container.
Writes ``reports/<profile>/chatbot_sample_answers.md`` so the README can quote the
sample answers. Skipped automatically when either service is unavailable.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from entdec.config import get_config

SAMPLE_QUERIES = [
    "Tôi thích Inception, gợi ý vài game có cốt truyện hay",
    "Phim kinh dị tâm lý giống Black Swan",
    "Game thế giới mở, khám phá, cho người thích The Witcher 3",
    "Muốn xem phim hài nhẹ nhàng cuối tuần",
    "Tôi hay chơi Hades, đề xuất phim cùng phong cách",
]

# the sample queries are cross-domain on purpose (spec section 8)
EXPECTED_DOMAIN = ["game", "movie", "game", "movie", "movie"]

REASONING_MARKERS = ("Okay", "Wait", "Let me", "Let's", "The user wants", "I need to")

pytestmark = pytest.mark.integration


def _services_available() -> bool:
    cfg = get_config("tiny", use_cache=False)
    from entdec.graph.neo4j_client import Neo4jClient
    from entdec.nlp.ollama_client import OllamaClient

    try:
        ollama_ok = OllamaClient.from_config(cfg).health()
    except Exception:  # noqa: BLE001
        ollama_ok = False
    try:
        with Neo4jClient.from_config(cfg) as client:
            graph_ok = client.is_ready()
    except Exception:  # noqa: BLE001
        graph_ok = False
    return ollama_ok and graph_ok


def test_sample_queries_end_to_end() -> None:
    if not _services_available():
        pytest.skip("Ollama and/or the Neo4j container are not available")
    cfg = get_config("tiny", use_cache=False)
    from entdec.chatbot.pipeline import ChatPipeline

    pipeline = ChatPipeline(cfg)
    lines = [
        "# Chatbot sample answers (spec section 8)",
        "",
        "Generated by `python -m pytest tests/test_chatbot_integration.py -m integration` on profile `tiny`.",
        "",
    ]
    from entdec.llm.generator import LIST_LINE_RE, is_vietnamese

    for index, question in enumerate(SAMPLE_QUERIES, start=1):
        result = pipeline.run(question)
        retrieved = {item.title for item in result.items}
        # the requested domain must be the one that was searched
        assert EXPECTED_DOMAIN[index - 1] in result.domains_queried
        assert result.items, f"no recommendation for {question!r}"
        # the answer must be written in Vietnamese, without reasoning leakage
        assert is_vietnamese(result.answer), f"answer is not Vietnamese: {result.answer!r}"
        body = [line for line in result.answer.splitlines() if line.strip()]
        if result.answer_llm:
            assert body, "empty answer"
            for line in body:
                assert LIST_LINE_RE.match(line), f"prose leaked into the answer: {line!r}"
        for marker in REASONING_MARKERS:
            assert marker not in result.answer, f"reasoning leaked: {marker!r}"
        assert len(body) <= len(result.items) + 2, "answer lists more lines than items"
        # the reference items legitimately appear in evidence lines ("similar
        # to Black Swan (0.71)"), so they are allowed in the answer as well -
        # both as the user typed them and as resolved against the catalogue
        allowed = retrieved | set(result.resolved_references)
        # grounding: no title outside the retrieved/allowed set may appear.
        # Allowed titles are scrubbed first so that "Half-Life: Alyx" does not
        # count as a mention of the other catalogue item "Half-Life".
        scrubbed = result.answer
        for title in sorted(allowed, key=len, reverse=True):
            scrubbed = scrubbed.replace(title, "")
        for domain in result.domains_queried:
            catalogue_titles = set(pipeline._ranker(domain).titles_by_id().values())
            for title in catalogue_titles - allowed:
                assert title not in scrubbed, (
                    f"unretrieved item leaked into the answer: {title!r}"
                )
        lines.append(f"## {index}. {question}")
        lines.append("")
        lines.append(f"**Resolved references:** {result.resolved_references}")
        lines.append("")
        lines.append(f"**Answer ({'LLM' if result.answer_llm else 'template'}, "
                     f"{'graph' if result.used_graph else 'local retrieval'}):**\n{result.answer}")
        lines.append("")
        lines.append("| # | item | evidence |")
        lines.append("|---|------|----------|")
        for rank, item in enumerate(result.items, start=1):
            lines.append(f"| {rank} | {item.title} | {item.evidence_line(result.language)} |")
        lines.append("")
        lines.append(
            f"intent: {result.intent.model_dump()} · "
            f"durations: { {k: round(v, 1) for k, v in result.durations.items()} }"
        )
        lines.append("")
    output = Path(cfg.paths.reports) / "chatbot_sample_answers.md"
    output.write_text("\n".join(lines), encoding="utf-8")
    assert output.exists()
