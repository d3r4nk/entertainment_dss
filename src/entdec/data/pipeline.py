"""The ``data`` pipeline step: both domains -> Parquet + a stats report."""

from __future__ import annotations

import json
from dataclasses import asdict
from typing import Any

import pandas as pd

from entdec.config import Config
from entdec.data import movielens, steam
from entdec.logging_setup import get_logger

logger = get_logger(__name__)

DATA_STATS_MD = "data_stats.md"
DATA_STATS_JSON = "data_stats.json"


def _density(n_interactions: int, n_users: int, n_items: int) -> float:
    """Interaction density of the sampled user-item matrix, in percent."""
    if not n_users or not n_items:
        return 0.0
    return 100.0 * n_interactions / (n_users * n_items)


def _game_tag_sources(cfg: Config) -> dict[str, int]:
    """Count game tags per origin (``steam`` vs ``propagated``)."""
    path = cfg.paths.processed / steam.GAME_TAGS_PARQUET
    if not path.exists():
        return {}
    try:
        tags = pd.read_parquet(path, columns=["app_id", "source"])
    except (OSError, ValueError, KeyError):
        return {}
    counts = tags.drop_duplicates(["app_id", "source"])["source"].value_counts()
    return {str(key): int(value) for key, value in counts.items()}


def build_report(cfg: Config, movies: movielens.MovieStats, games: steam.GameStats) -> str:
    """Render ``reports/data_stats.md``."""
    sources = _game_tag_sources(cfg)
    notes = [
        "- Movie side: genres come from MovieLens, themes from the tag genome and",
        "  free-text user tags.",
    ]
    if sources:
        notes += [
            "- Game side: `games_metadata.json` has no tags *and* no description for a",
            "  large share of the most popular games (this snapshot: 1,244 of 50,872 entries",
            "  overall, but ~63% of the top 500 by review count). Those tags are completed",
            "  from co-review neighbours (`source = propagated`, see `entdec/data/enrich.py`).",
            f"  Games with Steam tags: {sources.get('steam', 0)}; "
            f"completed by propagation: {sources.get('propagated', 0)}.",
        ]

    rows = [
        ("profile", cfg.profile.name),
        ("max items per domain", cfg.profile.max_items),
        ("max users per domain", cfg.profile.max_users),
        ("min interactions / user", cfg.profile.min_interactions_per_user),
        ("min positives / user", cfg.profile.min_positive_per_user),
        ("movie positive rule", f"rating >= {cfg.get('positive.movie_min_rating', 4.0)}"),
        (
            "game positive rule",
            "is_recommended == True"
            + (f" and hours >= {cfg.get('positive.game_min_hours', 0.0)}"),
        ),
    ]

    lines = [
        "# Dataset statistics",
        "",
        f"Generated by `python -m entdec data --profile {cfg.profile.name}`.",
        "",
        "## Configuration",
        "",
        "| setting | value |",
        "|---------|-------|",
        *(f"| {key} | {value} |" for key, value in rows),
        "",
        "## Domains",
        "",
        "| metric | movies | games |",
        "|--------|--------|-------|",
        f"| items | {movies.n_items:,} | {games.n_items:,} |",
        f"| users | {movies.n_users:,} | {games.n_users:,} |",
        f"| interactions | {movies.n_interactions:,} | {games.n_interactions:,} |",
        f"| positive interactions | {movies.n_positives:,} | {games.n_positives:,} |",
        f"| positive ratio | {_ratio(movies.n_positives, movies.n_interactions):.1f}% "
        f"| {_ratio(games.n_positives, games.n_interactions):.1f}% |",
        f"| train rows | {movies.splits.get('train', 0):,} | {games.splits.get('train', 0):,} |",
        f"| validation rows | {movies.splits.get('valid', 0):,} | {games.splits.get('valid', 0):,} |",
        f"| test rows | {movies.splits.get('test', 0):,} | {games.splits.get('test', 0):,} |",
        f"| density (user x item) | {_density(movies.n_interactions, movies.n_users, movies.n_items):.2f}% "
        f"| {_density(games.n_interactions, games.n_users, games.n_items):.2f}% |",
        "",
        "## Notes",
        "",
        *notes,
        "",
    ]
    return "\n".join(lines)


def _ratio(positives: int, total: int) -> float:
    return 100.0 * positives / total if total else 0.0


def _movie_stats_from_disk(cfg: Config) -> movielens.MovieStats:
    """Rebuild the movie stats from existing Parquet artefacts (no rebuild)."""
    processed = cfg.paths.processed
    movies_path = processed / movielens.MOVIES_PARQUET
    ratings_path = processed / movielens.MOVIE_RATINGS_PARQUET
    if not (movies_path.exists() and ratings_path.exists()):
        return movielens.MovieStats()
    movies = pd.read_parquet(movies_path, columns=["movie_id"])
    ratings = pd.read_parquet(ratings_path, columns=["uid", "is_positive", "split"])
    counts = ratings["split"].value_counts()
    return movielens.MovieStats(
        n_items=len(movies),
        n_users=int(ratings["uid"].nunique()),
        n_interactions=len(ratings),
        n_positives=int(ratings["is_positive"].sum()),
        splits={name: int(counts.get(name, 0)) for name in ("train", "valid", "test")},
    )


def _game_stats_from_disk(cfg: Config) -> steam.GameStats:
    """Rebuild the game stats from existing Parquet artefacts (no rebuild)."""
    processed = cfg.paths.processed
    games_path = processed / steam.GAMES_PARQUET
    reviews_path = processed / steam.GAME_REVIEWS_PARQUET
    if not (games_path.exists() and reviews_path.exists()):
        return steam.GameStats()
    games = pd.read_parquet(games_path, columns=["app_id"])
    reviews = pd.read_parquet(reviews_path, columns=["uid", "is_positive", "split"])
    counts = reviews["split"].value_counts()
    return steam.GameStats(
        n_items=len(games),
        n_users=int(reviews["uid"].nunique()),
        n_interactions=len(reviews),
        n_positives=int(reviews["is_positive"].sum()),
        splits={name: int(counts.get(name, 0)) for name in ("train", "valid", "test")},
    )


def run(cfg: Config, args: Any = None) -> int:
    """Run the data preparation step for both domains."""
    force = bool(getattr(args, "force", False))

    movies = movielens.run(cfg, force=force)
    games = steam.run(cfg, force=force)
    if not movies.n_items:
        movies = _movie_stats_from_disk(cfg)
    if not games.n_items:
        games = _game_stats_from_disk(cfg)

    if not movies.n_items or not games.n_items:
        logger.error(
            "data step incomplete (movies=%d items, games=%d items)",
            movies.n_items,
            games.n_items,
        )
        return 1

    report = build_report(cfg, movies, games)
    report_path = cfg.report_path(DATA_STATS_MD)
    report_path.write_text(report, encoding="utf-8")
    stats_path = cfg.report_path(DATA_STATS_JSON)
    stats_path.write_text(
        json.dumps(
            {"profile": cfg.profile.name, "movies": asdict(movies), "games": asdict(games)},
            indent=2,
        ),
        encoding="utf-8",
    )
    logger.info("wrote %s and %s", report_path.name, stats_path.name)
    return 0


__all__ = ["DATA_STATS_JSON", "DATA_STATS_MD", "build_report", "run"]
